#!/usr/bin/env node
// The label-free monitor: what the verification log says every day, whether
// or not anyone rated anything.
//
// Ratings only ever see what editors chose to rate, and almost nobody rates a
// SOURCE UNAVAILABLE. So the two biggest movements of autumn 2026 — Wayback
// throttling the proxy (20–37% of archive.org fetches failing for weeks), and
// SOURCE UNAVAILABLE rising to 39% after the default model changed — were
// invisible to feedback and visible in the log from day one. This compares
// the last N days with the M before them, per model, and says when something
// moved.
//
//   node feedback-loop/monitor.js sql [--days 7] [--baseline-days 28]   > monitor.sql
//   psql "$NEON_LOOP_DATABASE_URL" -X -q -At -v ON_ERROR_STOP=1 -f monitor.sql > snapshot.json
//   node feedback-loop/monitor.js report --snapshot snapshot.json \
//        [--previous-body previous.md] [--out body.md] [--comment-out comment.md]
//
// The pattern counts come from causes.js's causeSql(), so they are exactly
// what triage tags. The SQL is generated rather than kept in a .sql file for
// that reason: there is no second copy of a pattern to drift.

import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { CAUSE_RULES, causeRule, causeSql, sqlIsExact } from './causes.js';
import { md } from './report.js';

const FETCH_FAILED = causeSql(causeRule('fetch_failed'));
// Rules other than fetch_failed, which the verdict breakdown already shows.
const PATTERN_RULES = CAUSE_RULES.filter(r => r.id !== 'fetch_failed');

// The host a source lives on, looking through a Wayback URL (as causes.js's
// sourceHost() does in JS).
const HOST_SQL = "coalesce(substring(source_url from 'web\\.archive\\.org/web/[^/]+/(?:https?://)?(?:www\\.)?([^/:?#]+)'), "
    + "regexp_replace(split_part(split_part(source_url, '://', 2), '/', 1), '^www\\.', ''))";

export function buildMonitorSql({ days = 7, baselineDays = 28 } = {}) {
    const d = Math.max(1, Math.floor(Number(days)));
    const total = d + Math.max(1, Math.floor(Number(baselineDays)));
    const win = ts => `CASE WHEN ${ts} >= now() - interval '${d} days' THEN 'current' ELSE 'baseline' END`;
    const ruleColumns = PATTERN_RULES.map(r => `         count(*) FILTER (WHERE ${causeSql(r)}) AS ${r.id}`).join(',\n');
    return `-- Generated by feedback-loop/monitor.js (buildMonitorSql). Do not edit by hand.
WITH base AS (
  SELECT *, ${win('ts')} AS win, coalesce(model, provider, 'unknown') AS m
  FROM verification_logs
  WHERE check_id IS NOT NULL AND ts >= now() - interval '${total} days'
),
by_model AS (
  SELECT win, m AS model, count(*) AS checks,
         count(*) FILTER (WHERE verdict = 'SUPPORTED') AS supported,
         count(*) FILTER (WHERE verdict = 'PARTIALLY SUPPORTED') AS partially,
         count(*) FILTER (WHERE verdict = 'NOT SUPPORTED') AS not_supported,
         count(*) FILTER (WHERE verdict = 'SOURCE UNAVAILABLE') AS unavailable,
         count(*) FILTER (WHERE ${FETCH_FAILED}) AS fetch_failed,
${ruleColumns}
  FROM base GROUP BY win, m
),
hosts AS (
  SELECT ${HOST_SQL} AS host, count(*) AS checks, count(*) FILTER (WHERE ${FETCH_FAILED}) AS fetch_failed
  FROM base WHERE win = 'current' AND source_url IS NOT NULL
  GROUP BY 1
),
fb AS (
  SELECT ${win('f.ts')} AS win,
         count(*) FILTER (WHERE f.rating = 1) AS up,
         count(*) FILTER (WHERE f.rating = -1) AS down,
         count(*) FILTER (WHERE f.corrected_verdict IS NOT NULL) AS corrections,
         count(*) FILTER (WHERE f.rating IS NOT NULL AND l.verdict IN ('NOT SUPPORTED', 'PARTIALLY SUPPORTED')) AS rated_flags,
         count(*) FILTER (WHERE f.rating = -1 AND l.verdict IN ('NOT SUPPORTED', 'PARTIALLY SUPPORTED')) AS down_on_flags
  FROM feedback f LEFT JOIN verification_logs l USING (check_id)
  WHERE f.ts >= now() - interval '${total} days'
  GROUP BY 1
)
SELECT json_build_object(
  'generated_at', now(),
  'window_days', ${d},
  'baseline_days', ${total - d},
  'models', (SELECT coalesce(json_agg(b ORDER BY b.win, b.checks DESC), '[]'::json) FROM by_model b),
  'failing_hosts', (SELECT coalesce(json_agg(h ORDER BY h.fetch_failed DESC, h.host), '[]'::json)
                    FROM (SELECT * FROM hosts WHERE fetch_failed > 0 ORDER BY fetch_failed DESC, host LIMIT 15) h),
  'feedback', (SELECT coalesce(json_agg(fb), '[]'::json) FROM fb)
);
`;
}

// First guesses, each set to catch an incident already seen (see the header).
// Recalibrate against past snapshots, not by loosening a test.
export const DEFAULT_THRESHOLDS = Object.freeze({
    minChecks: 200,       // a model needs this many checks in both windows to be compared
    // A model arriving or leaving alerts only at this share of all checks —
    // a new default (Qwen3.8 in October), not one person's own API key
    // (claude-sonnet-4-6's 535 checks were 2% of the baseline).
    modelShare: 0.10,
    sharePoints: 8,       // a verdict or fetch-failure share moving this many points alerts
    patternFactor: 1.5,   // a pattern rate rising by this factor...
    patternPoints: 2,     // ...and by at least this many points alerts
    minRatedFlags: 20,    // flags rated in the window before their thumbs-down share counts
    downPoints: 15,       // thumbs-down share on rated flags moving this many points alerts
});

const SHARES = Object.freeze([
    ['unavailable', 'SOURCE UNAVAILABLE'],
    ['fetch_failed', 'fetch failed before any model call'],
    ['model_unavailable', 'SOURCE UNAVAILABLE said by the model'],
    ['not_supported', 'NOT SUPPORTED'],
    ['partially', 'PARTIALLY SUPPORTED'],
    ['supported', 'SUPPORTED'],
]);

const num = v => Number(v ?? 0) || 0;

function withDerived(row) {
    const r = { ...row };
    for (const key of ['checks', 'supported', 'partially', 'not_supported', 'unavailable', 'fetch_failed', ...PATTERN_RULES.map(p => p.id)]) {
        r[key] = num(r[key]);
    }
    r.model_unavailable = Math.max(0, r.unavailable - r.fetch_failed);
    return r;
}

function sumRows(rows, model) {
    const out = { model, checks: 0 };
    for (const row of rows) {
        for (const [k, v] of Object.entries(row)) if (typeof v === 'number') out[k] = (out[k] ?? 0) + v;
    }
    return out;
}

/** The snapshot as per-window maps of model -> counts, with an "all models" row. */
export function indexSnapshot(snapshot) {
    const windows = { current: new Map(), baseline: new Map() };
    for (const raw of snapshot.models ?? []) {
        const row = withDerived(raw);
        windows[raw.win === 'current' ? 'current' : 'baseline'].set(row.model, row);
    }
    for (const w of Object.values(windows)) w.set('all models', sumRows([...w.values()], 'all models'));
    const feedback = { current: null, baseline: null };
    for (const f of snapshot.feedback ?? []) feedback[f.win === 'current' ? 'current' : 'baseline'] = f;
    return { ...windows, feedback };
}

const share = (row, key) => (row && row.checks ? row[key] / row.checks : 0);
const points = x => Math.round(x * 1000) / 10;

/**
 * Alerts, each with a stable `key` (what moved, not by how much), so a
 * standing alert can be recognized from one day to the next.
 */
export function evaluateAlerts(snapshot, thresholds = DEFAULT_THRESHOLDS) {
    const t = { ...DEFAULT_THRESHOLDS, ...thresholds };
    const { current, baseline, feedback } = indexSnapshot(snapshot);
    const alerts = [];
    const totalNow = current.get('all models')?.checks ?? 0;
    const totalBefore = baseline.get('all models')?.checks ?? 0;
    const shareOf = (row, total) => (row && total ? row.checks / total : 0);

    // Arrived: a real share now, under a tenth of it before. Left: the mirror.
    // Relative, so a former default dropping from 57% to 17% (still running,
    // still compared below) is not "gone", while 100% to 6% is.
    for (const [model, cur] of current) {
        if (model === 'all models') continue;
        const now = shareOf(cur, totalNow);
        const before = shareOf(baseline.get(model), totalBefore);
        if (now >= t.modelShare && before < now / 10) {
            alerts.push({ key: `new-model:${model}`, kind: 'new_model', model, text: `${model} ran ${points(now)}% of checks this window, up from ${points(before)}%: every rate below shifts with it.` });
        }
    }
    for (const [model, base] of baseline) {
        if (model === 'all models') continue;
        const before = shareOf(base, totalBefore);
        const now = shareOf(current.get(model), totalNow);
        if (before >= t.modelShare && now < before / 10) {
            alerts.push({ key: `gone-model:${model}`, kind: 'gone_model', model, text: `${model} ran ${points(before)}% of checks in the baseline and ${points(now)}% this window.` });
        }
    }

    for (const [model, cur] of current) {
        const base = baseline.get(model);
        if (!base || cur.checks < t.minChecks || base.checks < t.minChecks) continue;
        for (const [metric, label] of SHARES) {
            const delta = share(cur, metric) - share(base, metric);
            if (Math.abs(delta) * 100 >= t.sharePoints) {
                const dir = delta > 0 ? 'up' : 'down';
                alerts.push({
                    key: `share:${model}:${metric}:${dir}`, kind: 'share', model, metric,
                    base: points(share(base, metric)), current: points(share(cur, metric)),
                    text: `${model}: ${label} ${dir} from ${points(share(base, metric))}% to ${points(share(cur, metric))}% of checks.`,
                });
            }
        }
        for (const rule of PATTERN_RULES) {
            const b = share(base, rule.id);
            const c = share(cur, rule.id);
            if (c >= b * t.patternFactor && (c - b) * 100 >= t.patternPoints) {
                alerts.push({
                    key: `pattern:${model}:${rule.id}`, kind: 'pattern', model, rule: rule.id,
                    base: points(b), current: points(c),
                    text: `${model}: "${rule.label}" up from ${points(b)}% to ${points(c)}% of checks.`,
                });
            }
        }
    }
    const fc = feedback.current;
    const fb = feedback.baseline;
    if (fc && fb && num(fc.rated_flags) >= t.minRatedFlags && num(fb.rated_flags) >= t.minRatedFlags) {
        const c = num(fc.down_on_flags) / num(fc.rated_flags);
        const b = num(fb.down_on_flags) / num(fb.rated_flags);
        if (Math.abs(c - b) * 100 >= t.downPoints) {
            const dir = c > b ? 'up' : 'down';
            alerts.push({ key: `feedback:down-on-flags:${dir}`, kind: 'feedback', base: points(b), current: points(c), text: `Thumbs-down on rated flags ${dir} from ${points(b)}% to ${points(c)}%.` });
        }
    }
    return alerts;
}

export function alertFingerprint(alerts) {
    const keys = alerts.map(a => a.key).sort().join('\n');
    return createHash('sha256').update(keys).digest('hex').slice(0, 16);
}

const FINGERPRINT_RE = /<!-- monitor-alerts: ([0-9a-f]+|none) -->/;

/** Comment (and so notify) only when the set of alerts changed since the last body. */
export function shouldComment(alerts, previousBody = '') {
    if (!alerts.length) return false;
    const previous = String(previousBody).match(FINGERPRINT_RE)?.[1] ?? null;
    return previous !== alertFingerprint(alerts);
}

const pct = (n, d) => (d ? `${points(n / d)}%` : '—');

function modelTable(current, baseline) {
    const rows = [...current.values()].filter(r => r.checks > 0).sort((a, b) => (a.model === 'all models') - (b.model === 'all models') || b.checks - a.checks);
    const lines = ['| Model | Checks | Supported | Partially | Not supported | Unavailable (fetch / model) | Unavailable before |', '|---|---|---|---|---|---|---|'];
    for (const r of rows) {
        const b = baseline.get(r.model);
        lines.push(`| ${md(r.model)} | ${r.checks} | ${pct(r.supported, r.checks)} | ${pct(r.partially, r.checks)} | ${pct(r.not_supported, r.checks)} | ${pct(r.unavailable, r.checks)} (${pct(r.fetch_failed, r.checks)} / ${pct(r.model_unavailable, r.checks)}) | ${b ? pct(b.unavailable, b.checks) : '—'} |`);
    }
    return lines.join('\n');
}

function patternTable(current, baseline) {
    const cur = current.get('all models');
    const base = baseline.get('all models');
    const lines = ['| Pattern | Brief | Now | Before |', '|---|---|---|---|'];
    for (const rule of PATTERN_RULES) {
        const note = sqlIsExact(rule) ? '' : ' (lower bound)';
        lines.push(`| ${md(rule.label)}${note} | ${rule.brief ? `cause ${rule.brief}` : '—'} | ${pct(cur?.[rule.id] ?? 0, cur?.checks)} | ${pct(base?.[rule.id] ?? 0, base?.checks)} |`);
    }
    return lines.join('\n');
}

function hostTable(hosts) {
    if (!hosts?.length) return '_No fetch failures this window._';
    const lines = ['| Host | Failed fetches | Checks | Share failed |', '|---|---|---|---|'];
    for (const h of hosts) lines.push(`| ${md(h.host ?? '?')} | ${num(h.fetch_failed)} | ${num(h.checks)} | ${pct(num(h.fetch_failed), num(h.checks))} |`);
    return lines.join('\n');
}

export function renderMonitorReport(snapshot, alerts) {
    const { current, baseline, feedback } = indexSnapshot(snapshot);
    const days = snapshot.window_days ?? 7;
    const before = snapshot.baseline_days ?? 28;
    const fc = feedback.current;
    const out = [
        '# Verification monitor', '',
        `Updated ${String(snapshot.generated_at ?? '').slice(0, 16).replace('T', ' ')} UTC. The last ${days} days, compared with the ${before} before. Generated by \`feedback-loop/monitor.js\`; this body is replaced daily, and a comment is posted when the set of alerts changes.`, '',
        `## Alerts (${alerts.length})`, '',
        alerts.length ? alerts.map(a => `- ${md(a.text)}`).join('\n') : '_None._', '',
        `## Verdicts by model, last ${days} days`, '',
        modelTable(current, baseline), '',
        '## Patterns in the model\'s explanations, all models', '',
        'From `feedback-loop/causes.js`, the same rules triage tags. Unvalidated: read them as trends, not counts of errors.', '',
        patternTable(current, baseline), '',
        `## Fetch failures by host, last ${days} days`, '',
        hostTable(snapshot.failing_hosts), '',
        `## Feedback, last ${days} days`, '',
        fc ? `${num(fc.up)} 👍, ${num(fc.down)} 👎, ${num(fc.corrections)} corrected verdicts. Thumbs-down on rated flags: ${pct(num(fc.down_on_flags), num(fc.rated_flags))} of ${num(fc.rated_flags)}.` : '_No ratings this window._',
        '',
        `<!-- monitor-alerts: ${alerts.length ? alertFingerprint(alerts) : 'none'} -->`,
    ];
    return `${out.join('\n')}\n`;
}

export function renderAlertComment(alerts) {
    return `**Monitor: the alerts changed.**\n\n${alerts.map(a => `- ${md(a.text)}`).join('\n')}\n`;
}

function setGithubOutputs(values) {
    if (!process.env.GITHUB_OUTPUT) return;
    fs.appendFileSync(process.env.GITHUB_OUTPUT, Object.entries(values).map(([k, v]) => `${k}=${v}\n`).join(''));
}

function main() {
    const [command, ...rest] = process.argv.slice(2);
    const { values } = parseArgs({
        args: rest,
        options: {
            days: { type: 'string', default: '7' },
            'baseline-days': { type: 'string', default: '28' },
            snapshot: { type: 'string' },
            'previous-body': { type: 'string' },
            out: { type: 'string' },
            'comment-out': { type: 'string' },
        },
    });
    if (command === 'sql') {
        process.stdout.write(buildMonitorSql({ days: values.days, baselineDays: values['baseline-days'] }));
        return;
    }
    if (command === 'report' && values.snapshot) {
        const snapshot = JSON.parse(fs.readFileSync(values.snapshot, 'utf8'));
        const alerts = evaluateAlerts(snapshot);
        const body = renderMonitorReport(snapshot, alerts);
        if (values.out) fs.writeFileSync(values.out, body);
        else process.stdout.write(body);
        const previous = values['previous-body'] && fs.existsSync(values['previous-body'])
            ? fs.readFileSync(values['previous-body'], 'utf8') : '';
        const comment = shouldComment(alerts, previous);
        if (comment && values['comment-out']) fs.writeFileSync(values['comment-out'], renderAlertComment(alerts));
        setGithubOutputs({ alerts: alerts.length, comment });
        console.error(`${alerts.length} alert(s)${comment ? ', changed since the last run' : ''}`);
        return;
    }
    console.error('Usage: monitor.js sql [--days N --baseline-days M] | monitor.js report --snapshot FILE [--previous-body FILE] [--out FILE] [--comment-out FILE]');
    process.exit(1);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
